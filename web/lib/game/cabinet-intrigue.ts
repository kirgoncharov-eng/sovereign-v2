export function cabinetArc(state: CabinetStoryState, arc: Arc): Arc {
  if (arc.id !== 'mole' || state.country !== ALTERNATE_COUNTRY || state.daily) return arc;
  if (!outsideCouncil(state)) return { ...arc, beats: arc.beats.map(beat => beat.turn !== 7 ? beat : {
    ...beat, variants: beat.variants.map(variant => ({ ...variant,
      choices: variant.choices.map(choice => choice.flag !== 'purge' || !variant.requires?.includes('watch') ? choice
        : { ...choice, ...TRACE.choices.purge }),
    })),
  }) };
  return { ...arc,
    secret: 'Источник утечек — {target}. Он не входит в действующий совет, но сохраняет старые документы и связи в аппарате. Не объявляй его виновным до раскрытия следа.',
    hooks: [
      'В журнале исходящих обнаружилась копия без подписи получателя. Курьер помнит адрес, но не фамилию.',
      'Охрана вернула старый пропуск. Из телефонного справочника этот номер никто не вычеркнул.',
      'Руководитель отдела просит подтвердить старый список рассылки. Он привык считать молчание согласием.',
      'За границей цитируют неопубликованный проект. На нём ещё нет вашей подписи.',
      'Шифровальщик принёс список служебных звонков за прошлый год. Несколько номеров записаны карандашом.',
      'Водитель заметил знакомую машину у бокового входа в министерство. В резиденцию она больше не приезжает.',
      'Новая опись архива короче старой на одну папку. Архивариус просит не подписывать акт до пересчёта.',
      'Вы перечитываете список допущенных. Он стал короче; записные книжки служащих остались прежними.',
    ],
    beats: arc.beats.map(beat => ({ ...beat, variants: beat.variants.map(variant => {
      const copy = beat.turn === 1 ? OPENING : beat.turn === 3 ? LEAK
        : beat.turn === 7 ? variant.requires?.includes('watch') ? TRACE : HEALTH
        : beat.turn === 12 ? PRESSURE : variant.requires ? EXPOSED : PUBLISHED;
      return { ...variant, title: copy.title, description: copy.description,
        choices: variant.choices.map(choice => ({ ...choice, ...copy.choices[choice.flag] })) };
    }) })),
  };
}

