import type { ResourceKey } from '../game/types.ts';

export type LifeBand = 'low' | 'mid' | 'high';

export interface LifePlace {
  id: string;
  /** Опора, по которой живёт место: её уровень к концу квартала выбирает строку. */
  resource: ResourceKey;
  /**
   * Границы уровней: ниже `low` — плохо, выше `high` — хорошо. У каждой опоры свои: замер 72 партий первого срока
   * (#310) — экономика держится между 27 и 43, силовики — между 39 и 47, легитимность — между 33 и 63.
   */
  low: number;
  high: number;
  /** Кварталы срока (1–20), в которые место может появиться в ленте. */
  turns: number[];
  /** Первое появление: каким игрок застаёт место. */
  first: Record<LifeBand, string>;
  /** С прошлого раза стало лучше: до среднего и до высокого уровня. */
  up: Record<'mid' | 'high', string>;
  /** С прошлого раза стало хуже: до среднего и до низкого уровня. */
  down: Record<'mid' | 'low', string>;
  /** Уровень прежний: один раз, дальше место молчит, пока что-то не изменится. */
  same: Record<LifeBand, string>;
}

