import type { TraitId } from '../game/people.ts';
import type { ActionTag, Bloc, ResourceDelta } from '../game/types.ts';

export interface SubjectOption {
  text: string;
  terms: string;      // что именно поручается, кто отвечает и что будет; цена в ресурсах дописывается движком
  tags: ActionTag[];
  res: ResourceDelta;
  figure: number;     // отношение собеседника
  camp: number;       // отношение его лагеря
  others?: Partial<Record<Bloc, number>>; // отношение других лагерей, которых решение касается
  scene: string;
  headline: string;
  report: { label: string; story: string; res: ResourceDelta; turns?: number };
}

export interface SubjectCall {
  situation: string;
  voice: Record<TraitId, string>;
  options: [SubjectOption, SubjectOption, SubjectOption];
  refuse: SubjectOption;
  later: SubjectOption;
}

