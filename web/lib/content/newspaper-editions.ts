type HeadlineFactory = (event: string, choice: string) => string;

export const OUTCOME_HEADLINE: Record<"success" | "failure", readonly HeadlineFactory[]> = {
  success: [
    (event: string) => `${event}: решение исполнено`,
    (_event: string, choice: string) => `Исполнено: «${choice}»`,
  ],
  failure: [
    (event: string) => `${event}: решение сорвано`,
    (_event: string, choice: string) => `Подписано, но не исполнено: «${choice}»`,
  ],
} as const;
