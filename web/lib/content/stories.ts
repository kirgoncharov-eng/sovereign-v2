// Истории людей: личные сообщения, которые приходят между делами и тянутся несколько ходов.
// У человека своя жизнь — отставка, сын, долги города, книга, болезнь. Ваши решения в неё вмешиваются:
// следующее сообщение зависит от того, как вы с ним обошлись (отношения), и от того, как живёт страна.
//
// Слоты: {name} — имя, {role} — должность со строчной, {capital}, {faith:…} — как в остальном тексте,
// {sex:он|она} — по имени человека. Глаголы в настоящем времени, чтобы не зависеть от рода.
import type { Resources } from "../game/types.ts";
import type { RoleGroup } from "./roles.ts";

export type LetterKind = "letter" | "call" | "note" | "report";

// Что видно истории о стране и о человеке в момент сообщения.
export interface StoryContext {
  mood: "warm" | "cold" | "neutral"; // как человек к вам относится
  res: Resources;
  crisis: boolean; // идёт кризис или опора ниже 20
}

export interface StoryStep {
  kind: LetterKind;
  // Текст сообщения или null — шаг пропускается (например, тёплый эпилог при холодных отношениях).
  text: (ctx: StoryContext) => string | null;
}

export interface Story {
  id: string;
  // Чья история: человек из этой группы (кроме антагониста интриги) или кто-то из вашего окружения.
  who: RoleGroup | "self";
  ids?: string[];  // какие должности подходят, если группа шире истории
  sender?: string; // для «self»: кто пишет
  steps: StoryStep[];
}

const byMood = (warm: string, cold: string, neutral: string) => (c: StoryContext) =>
  c.mood === "warm" ? warm : c.mood === "cold" ? cold : neutral;

