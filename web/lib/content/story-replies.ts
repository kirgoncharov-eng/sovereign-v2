//
// Тексты продолжений пишутся сразу в реалиях 1978 года; слоты те же, что в stories.ts.
import type { ResourceDelta } from "../game/types.ts";
import type { StoryContext } from "./stories.ts";

export interface ReplyOption {
  id: string;
  text: string;            // резолюция, как её подписывает президент
  cost: ResourceDelta;     // цена ответа, видна до выбора
  relation?: number;       // как изменится отношение героя истории
  mood: StoryContext["mood"]; // по какой ветке пойдёт история после ответа
  // Свои тексты для следующих шагов (номер шага истории → текст): null — шаг пропускается,
  // undefined или нет записи — шаг идёт по общей ветке `mood`.
  steps?: Record<number, (context: StoryContext) => string | null | undefined>;
}

export interface StoryReplies {
  step: number; // на каком письме истории можно ответить
  options: [ReplyOption, ReplyOption];
}

