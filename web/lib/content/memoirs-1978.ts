function inflectGender(text: string, fem: boolean): string {
  if (!fem) return text;
  let res = text;
  for (const [pattern, replacement] of FEM_VERBS) res = res.replace(pattern, replacement);
  return res;
}

const AUTHORED_TITLES = new Set(ALTERNATE_EVENTS.map(e => e.title));

function formatDecisionMemory(entry: HistoryEntry, fem: boolean): string {
  const byTitle = CASE_CHOICE_MEMORIES[entry.title];
  const mem = byTitle?.[entry.choice];
  if (mem) {
    return inflectGender(entry.success === false ? mem.fail : mem.ok, fem);
  }
  const verb = entry.success === false
    ? (fem ? "пыталась провести решение" : "пытался провести решение")
    : (fem ? "подписала решение" : "подписал решение");
  return `в деле «${entry.title}» ${verb} «${entry.choice}»`;
}

function pickKeyDecisions(history: HistoryEntry[]): HistoryEntry[] {
  const authored = history.filter(h => AUTHORED_TITLES.has(h.title) || !!CASE_CHOICE_MEMORIES[h.title]);
  const pool = authored.length >= 2 ? authored : history.filter(h => !h.special);
  if (pool.length <= 3) return pool;
  const first = pool[0];
  const middle = pool[Math.floor(pool.length / 2)];
  const last = pool[pool.length - 1];
  return [first, middle, last];
}

function formatArcMemory(state: GameState, fem: boolean): string {
  const arc = state.arc?.id === "alt_contracts" ? state.arc : null;
  const pastEpilogue = state.reign?.arcs.includes("alt_contracts") ? state.reign.epilogues[0] : null;
  const epilogue = arc?.epilogue ?? pastEpilogue ?? null;
  const target = arc?.target ? `, где фигурировал директор концерна ${arc.target},` : "";
  if (epilogue) {
    // Превращаем «Вы нашли…» в третье лицо для мемуаров.
    const third = epilogue
      .replace(/^Вы сменили /, fem ? "она сменила " : "он сменил ")
      .replace(/^Вы договорились /, fem ? "она договорилась " : "он договорился ")
      .replace(/^Вы нашли /, fem ? "она нашла " : "он нашёл ")
      .replace(/^Вы заставили /, fem ? "она заставила " : "он заставил ")
      .replace(/^Вы сохранили /, fem ? "она сохранила " : "он сохранил ")
      .replace(/^Вы закрыли /, fem ? "она закрыла " : "он закрыл ")
      .replace(/^Вы выбрали /, fem ? "она выбрала " : "он выбрал ")
      .replace(/^Вы попытались /, fem ? "она попыталась " : "он попытался ")
      .replace(/ и отделили /g, fem ? " и отделила " : " и отделил ");
    const sentence = third.charAt(0).toLowerCase() + third.slice(1);
    return `В сквозном деле «Четвёртый экземпляр»${target} ${sentence}`;
  }
  if (arc && arc.done.length > 0) {
    return `Расследование «Четвёртый экземпляр»${target} осталось незавершённым: спорная папка договора 1956 года так и не дошла до финального приговора.`;
  }
  return "";
}

function roleLower(role: string): string {
  return role.charAt(0).toLowerCase() + role.slice(1);
}

function formatPeopleMemory(figures: Figure[]): string {
  if (figures.length < 2) return "";
  const sorted = [...figures].sort((a, b) => b.relation - a.relation);
  const ally = sorted[0];
  const foe = sorted[sorted.length - 1];
  const allyFem = isFemaleName(ally.name);
  const foeFem = isFemaleName(foe.name);
  const allyDesc = `${ally.name} (${roleLower(ally.role)})`;
  const foeDesc = `${foe.name} (${roleLower(foe.role)})`;

  const allyClause = ally.relation >= 25
    ? `главной опорой кабинета к финалу ${allyFem ? "оставалась" : "оставался"} ${allyDesc}`
    : ally.relation >= 0
      ? `ближе других к кабинету к концу правления ${allyFem ? "держалась" : "держался"} ${allyDesc}`
      : `даже наиболее ${allyFem ? "терпимая" : "терпимый"} к кабинету ${allyDesc} к концу срока ${allyFem ? "говорила" : "говорил"} с резиденцией сквозь зубы`;

  const foeClause = foe.relation <= -25
    ? `а самым непримиримым противником ${foeFem ? "стала" : "стал"} ${foeDesc}`
    : `а холоднее всех решения президента ${foeFem ? "встречала" : "встречал"} ${foeDesc}`;

  return `В людях этот курс провёл чёткую межу: ${allyClause}, ${foeClause}.`;
}

function joinDecisionClauses(clauses: string[]): string {
  if (clauses.length === 0) return "";
  if (clauses.length === 1) return clauses[0];
  if (clauses.length === 2) return `${clauses[0]}, а затем ${clauses[1]}`;
  return `${clauses[0]}, в середине срока ${clauses[1]}, а затем ${clauses[2]}`;
}

export function buildMemoirVerdict1978(
  state: GameState,
  openingSentence: string,
  reignSentence: string,
  referenceItems: string[],
): string {
  const fem = isFemaleName(state.leader.name);
  const picked = pickKeyDecisions(state.history);
  const decisionsSentence = picked.length > 0
    ? `Лицо этого правления определили конкретные папки на президентском столе: ${state.leader.name.split(" ")[0]} ${joinDecisionClauses(picked.map(h => formatDecisionMemory(h, fem)))}.`
    : "";

  const arcSentence = formatArcMemory(state, fem);
  const peopleSentence = formatPeopleMemory(state.keyFigures);
  const secretaryLine = state.world?.secretary?.finale ?? "";

  const narrative = [
    openingSentence,
    reignSentence,
    decisionsSentence,
    arcSentence,
    peopleSentence,
    secretaryLine,
  ].filter(Boolean).join(" ");

  const reference = referenceItems.filter(Boolean).join(" ");
  return reference ? `${narrative}\n\nСправка архива: ${reference}` : narrative;
}
