// Название для варианта дела; без записи — общее.
export const historicalDelayedLabel = (choiceText: string, label: string): string =>
  HISTORICAL_DELAYED_LABELS[choiceText]?.[label] ?? label;

export function historicalEcho(country: string, pending: Pending): string | null {
  if (country !== ALTERNATE_COUNTRY || pending.story) return null;
  const card = ALTERNATE_EVENTS.find(event => event.title === pending.event);
  if (!card) return null;
  const echoes = HISTORICAL_ECHOES[card.id]?.[pending.source];
  // Эхо записано под общим названием; в ведомости стоит авторское, а сохранения 8.22 и раньше — общее.
  const generic = Object.entries(HISTORICAL_DELAYED_LABELS[pending.source] ?? {}).find(([, shown]) => shown === pending.label)?.[0];
  return echoes?.[generic ?? pending.label] ?? null;
}
