export function historicalEcho(country: string, pending: Pending): string | null {
  if (country !== ALTERNATE_COUNTRY || pending.story) return null;
  const card = ALTERNATE_EVENTS.find(event => event.title === pending.event);
  return card ? HISTORICAL_ECHOES[card.id]?.[pending.source]?.[pending.label] ?? null : null;
}
