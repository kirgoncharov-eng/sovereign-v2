// Слоты, которые подставляет механика. Все — в именительном падеже.
export type SecretarySlot = 'secretary' | 'advisor' | 'advisorRole' | 'director' | 'figure' | 'figureRole';

export function fillSecretary(text: string, slots: Partial<Record<SecretarySlot, string>>): string {
  return text.replace(/\{(\w+)\}/g, (match, key: string) => slots[key as SecretarySlot] ?? match);
}

