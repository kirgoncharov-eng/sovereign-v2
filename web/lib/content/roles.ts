// Кто как реагирует, когда слов не нужно: параллельные сцены «тем временем» и молчаливые поступки.
// Человек действует сообразно своему месту: генерал не созывает митинг, лидер оппозиции не ходит
// на ваши совещания, посол не аплодирует в парламенте, митрополит не нанимает юристов.
// Слоты: {name} — имя, {role} — должность со строчной буквы. Глаголы в настоящем времени — без рода.

export type RoleGroup = "power" | "elite" | "outsider" | "envoy" | "investor" | "church";

// Должности ключевых игроков всех стран → к какому миру человек принадлежит.
const GROUPS: Record<RoleGroup, string[]> = {
  power: ["kgb", "interior", "sbu", "security", "knb", "general", "prosecutor"],
  elite: ["oligarch", "clan", "parliament", "speaker", "mayor", "akim", "bashkan", "shadow"],
  outsider: ["opp_leader", "activist", "journalist", "diaspora", "revanchist", "nat_leader"],
  envoy: ["amb_russia", "amb_usa", "amb_eu"],
  investor: ["investor"],
  church: ["patriarch", "catholicos", "mufti"],
};
export const roleGroup = (figureId: string): RoleGroup =>
  (Object.keys(GROUPS) as RoleGroup[]).find(g => GROUPS[g].includes(figureId)) ?? "elite";

