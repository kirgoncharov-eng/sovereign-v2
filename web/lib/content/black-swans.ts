// Срочное дело — обычная карточка `EventCard`; к ней донесения тумана, две версии правды и разоблачение по паре
// «решение × правда». Люди лебедей без имён: так они не делят фамилию ни с кем из партии (#242).
// Президент — «вы», без рода; персонажи — по должности.
import type { EventCard } from './events.ts';
import type { Bloc, ResourceDelta } from '../game/types.ts';

// У каждого вида источника постоянная слабость (раздел 3 документа):
// местные точны в деталях и ошибаются в масштабе, ведомство выгораживает себя, печать видит масштаб и путает мотивы.
export type DispatchKind = 'local' | 'office' | 'press';
export interface SwanDispatch {
    kind: DispatchKind;
    from: string;
    text: string;
}

// Что открывается через 1–2 хода. `tail` — флаг для условий будущих дел и писем (раздел 6 документа).
export interface SwanReveal {
    text: string;
    res: ResourceDelta;
    stance?: Partial<Record<Bloc, number>>;
    tail?: string;
}

export interface BlackSwan {
    id: string;
    card: EventCard;
    dispatches: [SwanDispatch, SwanDispatch, SwanDispatch];
    truths: [string, string];                 // А и Б — для движка, тестов и вычитки; игроку до разоблачения не показываются
    reveal: [SwanReveal, SwanReveal][];       // по варианту дела: [при правде А, при правде Б]
}

// Дело-хвост: приходит, если в партии поднят флаг.
export interface SwanTail {
    flag: string;
    afterTurns: [number, number];
    card: EventCard;
}

