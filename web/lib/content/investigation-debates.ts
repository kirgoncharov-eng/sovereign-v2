export function hasInvestigationDebate(state: GameState): boolean {
  return state.country === ALTERNATE_COUNTRY && !state.daily && state.currentEvent?.beat?.arcId === 'alt_contracts'
    && state.currentEvent.choices.every(choice => !!INVESTIGATION_DEBATES[choice.text]);
}
