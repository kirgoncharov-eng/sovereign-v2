//   {fig:блок} — имя ключевой фигуры из фракции этого блока, {fac:блок} — название фракции.
// Карточка с {fig:X}/{fac:X} автоматически доступна только странам, где есть фракция блока X.
import type { ActionTag, Bloc, IdeologyId, ResourceDelta, ResourceKey } from "../game/types.ts";

export interface CardCondition {
  low?: ResourceKey[];     // ресурс ниже 30
  high?: ResourceKey[];    // ресурс выше 60
  hostile?: Bloc;          // фракция блока настроена враждебно (≤ −40)
  friendly?: Bloc;         // фракция блока — союзник (≥ 40)
  crisis?: boolean;        // есть активный кризис
  minTurn?: number;
  maxTurn?: number;
  preElection?: boolean;   // до выборов 1–2 хода
  ideo?: IdeologyId[];
}

export interface CardChoice {
  text: string;
  hint: string;
  tags: ActionTag[];
  resolves?: boolean;      // закрывает первый активный кризис
}

export interface EventCard {
  id: string;
  countries?: string[];
  when?: CardCondition;
  weight?: number;
  source: string;
  title: string;
  description: string;
  choices: CardChoice[];
}

